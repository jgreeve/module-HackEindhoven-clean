// scripts/gen-registry.mjs — generate the Studio module registry.
//
// The core does not import a module directory directly. A module is an npm
// package declared in package.json; this script reads the @tablette/module-*
// dependencies, resolves each package's `studioModule` metadata and writes
// src/modules/registry.generated.ts. Opting a module in or out is therefore a
// package.json edit, not a source edit.
//
// Run automatically on predev, prebuild, pretypecheck and pretest:modules.
// STUDIO_MODULES=wikidata,wikimedia subsets the registry for demo/CI builds
// without editing the manifest.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { installedManifestPath } from "./resolve-package.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const output =
  process.env.STUDIO_REGISTRY_OUT ?? join(root, "src", "modules", "registry.generated.ts");

const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const subset = (process.env.STUDIO_MODULES ?? "")
  .split(",")
  .map((id) => id.trim())
  .filter(Boolean);

const dependencies = Object.keys(pkg.dependencies ?? {})
  .filter((name) => name.startsWith("@tablette/module-") && name !== "@tablette/module-sdk")
  .sort();

const entries = [];
const seen = new Set();

for (const name of dependencies) {
  const manifestPath = installedManifestPath(name);
  if (!existsSync(manifestPath)) {
    throw new Error(
      `module package ${name} is declared in package.json but not installed (run npm install)`,
    );
  }
  const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
  const meta = manifest.studioModule;
  if (!meta || typeof meta !== "object") {
    throw new Error(`${name} has no "studioModule" metadata in its package.json`);
  }
  const { id, entry, export: exportName } = meta;
  if (!id || !entry || !exportName) {
    throw new Error(`${name}: studioModule must declare id, entry and export`);
  }
  if (seen.has(id)) throw new Error(`duplicate Studio module id "${id}"`);
  seen.add(id);
  if (subset.length && !subset.includes(id)) continue;
  entries.push({ name, id, exportName });
}

// Fail on an unknown id in STUDIO_MODULES, so a typo cannot silently produce
// an empty registry.
if (subset.length) {
  const known = new Set(
    dependencies.map((name) => {
      const manifest = JSON.parse(
        readFileSync(installedManifestPath(name), "utf8"),
      );
      return manifest.studioModule.id;
    }),
  );
  for (const id of subset) {
    if (!known.has(id)) throw new Error(`STUDIO_MODULES names unknown module "${id}"`);
  }
}

const lines = [
  "// SPDX-FileCopyrightText: 2026 Milovann Yanatchkov",
  "// SPDX-License-Identifier: MIT",
  "",
  "// src/modules/registry.generated.ts — GENERATED by scripts/gen-registry.mjs.",
  "// Do not edit by hand: add or remove an @tablette/module-* dependency instead.",
  "",
  'import type { StudioModule } from "@tablette/module-sdk";',
  ...entries.map((entry) => `import { ${entry.exportName} } from "${entry.name}";`),
  "",
  "/** Installed module packages, in dependency order. */",
  "export const GENERATED_MODULES: StudioModule[] = [",
  ...entries.map((entry) => `  ${entry.exportName},`),
  "];",
  "",
];

writeFileSync(output, lines.join("\n"));

const ids = entries.map((entry) => entry.id);
console.log(
  `gen:modules — ${ids.length ? ids.join(", ") : "(none)"} -> src/modules/registry.generated.ts`,
);
